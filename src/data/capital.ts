const rungMap = new Map(RUNGS.map((r) => [r.id, r]));
const jobMap = new Map(JOBS.map((j) => [j.id, j]));

export function rungById(id: string): Rung | undefined {
  return rungMap.get(id);
}

export function jobById(id: string): Job | undefined {
  return jobMap.get(id);
}

export function ownerRungs(namedOnly: boolean): Rung[] {
  return RUNGS.filter((r) => {
    const ownerish =
      r.kind === "founder" ||
      r.kind === "heir" ||
      r.kind === "operator" ||
      r.kind === "investor" ||
      (r.kind === "composite" && r.netWorth >= 100_000);
    if (!ownerish) return false;
    if (namedOnly) return r.named;
    return true;
  });
}
